//! THE RE-READ (the link-sets design §5.6, §5.7) and THE REQUEST (§5.7).
//!
//! **The re-read.** At the confirmation the enumeration and the panel run
//! AGAIN over the same held selection, every test over what the draft still
//! arranges of it ([`Enumeration::selection`]; PUB-3.108) — the region read
//! with its stored-endset test, the read-through, the filter's claims, the
//! held removals — composed under the answers the first stood under, each
//! carried onto the part of the re-read's windows holding its words
//! ([`Enumeration::answers_onto`]), and the two answers are DIFFED: a link
//! no longer offered (gone or retracted), a candidate a claim of the
//! person's has since superseded, a held removal since undone, a link that
//! has arrived, the held runs against the one image in V-order — a run
//! absent, split, moved or re-ordered since the panel's reads — and a
//! window part named, un-named or named by another record since (its origin
//! published meanwhile), whose answer stands only where it left the words
//! out, are each a DIFFERENCE, a run standing whole at a second place since
//! the panel's reads among them (`enumerate`'s **The second places**;
//! PUB-3.108). Any difference is answered as a
//! [`Restatement`], data for the caller to confirm again over what is left;
//! nothing is sent on it. The image's places are the kept places the
//! request then carries per run of a named draft's identity; the `also`
//! drafts' images, read again beside it, give each its own list. Version
//! ⟨k⟩'s image is the first read's ([`Enumeration::base`]): a published
//! member's positions never change, so key (iii) and the fold are decided
//! at the re-read against the member the request's `base` names, read
//! once. The draft's recorded base and its standing are the caller's to
//! read again beside it ([`super::draft_base`], [`super::standing`]): a
//! base moved since the panel is handed to the re-read in
//! [`Inputs::base`], which images that member once, the first read's
//! image serving no other, and a moved base or standing rides the same
//! re-statement (D4 (b′)).
//!
//! **The request.** From the confirmed rows, the enumeration and the panel
//! composed under the answers at the windows' parts before anything is
//! taken from either ([`Enumeration::composed`], [`Panel::composed`]), so no
//! entry is composed from a key decided before the answers: the runs from
//! the held selection as the re-read placed them, in the draft's order
//! however they were held, the version holding what the re-statement showed
//! — a run the draft carries at several places once per place, each with
//! its own kept place, a split run as its pieces, each run cut around its
//! merge records,
//! which no publication carries as a run or with a kept place
//! ([`Enumeration::pieces`]), every named draft's run with the rendering
//! draft's kept place beside it (its own words and an `also` draft's
//! alike, which the rendering draft holds by identity), and, per draft
//! `also` names, THAT draft's own kept places in `also_places`, read off
//! its image, so the one commit re-windows every named draft at its own
//! places (skep #739; the Nelson way, B3-S10), no two places of one list
//! overlapping — a run a place encloses taking none, that place's re-window
//! covering its words (`disjoint_places`; PUB-3.9) — every part of a window
//! onto the person's own unpublished origin answered first (THE ANSWERS,
//! B3-S11 P2 (i): at a part a record names, THE COUNTERPART — the part
//! re-composed by reference to the record's `to`, in this document or
//! another, with its kept place beside it as a stray's, so the commit
//! re-windows the draft there through the record — or DROP, which leaves
//! the words out; at a part no record names, publish-first, which is NOT
//! this request and leaves it inert, DROP, or KEEP PRIVATE, which sends the
//! part as a window with no place beside it, a placeholder to readers; an
//! answer the part does not admit, or none, leaving the request inert
//! naming the part), each part composed by the core the merge library's
//! shot calls too ([`compose_part`]), a window the draft no longer arranges
//! carrying nothing and asked nothing (PUB-3.108); the twin pre-check re-composing what the
//! draft's records already name, read again just before the send — the cut
//! the enumeration composed the selection by over its own read of the
//! twins, so a stray stretch's offers were judged on the published words
//! the request sends; then `links` — each switched-on row's
//! offered links and the formatting line's marks, `home` the tag `member`
//! or the row's picked set, `from`/`to` read through the records and the
//! parts taken by their counterpart (`RecordWalk`) and spelled in the
//! address form, the I-span form or THE MEMBER-POSITION FORM for an end on
//! this shot's new words, spelled CANONICALLY from the client's own runs
//! (the lowest positions holding each value, consecutive positions merged),
//! an end's words on a part left out or awaiting its answer cut away as at
//! the selection's edge and a formatting mark's on a part kept behind a
//! placeholder cut at its edge, an end cut whole written as stored, `ty`
//! verbatim, `old` the original; a candidate the board refused by its
//! lineage at an earlier send left out ([`Confirmed::left_out`]);
//! `retract` the job list's marks, and beside it THE PRIVATE RIDER
//! `originals` (the link-sets design §5.7 (vi′)): each listed mark of the
//! formatting types' own original, found from the mark's accept claim at
//! the panel, with the rest no copy ever covered — in no signed row, the
//! board ending each at its home with the mark; `read_with` the switched-on rows'
//! destinations other than the edition, once each, none where the edition
//! is already read with it; `claim` where the caller asks it, at either
//! form — with `mint` and `account` at a first publication of a
//! free-standing draft, or at the document form where `doc` is an edition
//! holding no member yet (the owner's ruling (i); skep #692), the claim row
//! then homed in `doc`'s trunk by address, first in that home's group;
//! `supersede` the daughters the caller names, each one supersession claim
//! homed in the trunk and its group last in the trunk's (the merge bridge
//! lane), THE SKIP READ FIRST: `in_claims` at each daughter, one an active
//! claim of the person's own already names dropped from the list and so
//! from the body, as the board's plan skips it, so the body signed is the
//! body the board composes; `places` and `also_places` beside `runs`,
//! neither in the signed body; the signed body through the one body
//! builder, `entry_body_publication`, from the request AS BUILT; a fresh
//! `id`. INERT where the request changes nothing against its base — a place
//! in either list is a change, and so is a daughter claimed. A selection
//! the draft has wholly left builds nothing: every run of it placed absent
//! is the fault [`Fault::SelectionNotArranged`], the re-read having
//! re-stated it, so no request of an empty member is built over words the
