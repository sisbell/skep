/// Builds the request from the confirmed rows over the re-read's answer.
///
/// The enumeration and the panel are composed under `confirmed` first —
/// its answers at the windows' parts and its originals left out — and
/// every member is taken from that composition alone. The windows' parts
/// and their records are the enumeration's, taken as given: nothing is
/// read of an origin here.
///
/// # Errors
///
/// In this order, [`Fault::SelectionNotArranged`] with `index` 0 where the
/// selection held runs and the draft arranges nothing of any of them
/// (PUB-3.108): the re-read has re-stated each absent, and no request of an
/// empty member is built, no read sent; then the reads' faults, the twin
/// pre-check, the values, the base's image.
pub fn build(p: &Publisher<'_>, inputs: &Inputs, e: &Enumeration, panel: &Panel, confirmed: &Confirmed) -> Result<Built, Fault> {
    let door = Door::new(p.board, p.token);
    build_with(&door, p, inputs, e, panel, confirmed)
}

/// Builds the request as [`build`] builds it, and asks no price: the
/// request's [`Request::price`] is the default, which admits and says
/// nothing of the board. For a caller that holds the request to take its
/// switched lists again and price what it then is ([`Request::switched`],
/// [`price()`]) — the panel's count — and never sends it as built.
///
/// # Errors
///
/// [`build`]'s, the price's aside.
pub fn build_unpriced(p: &Publisher<'_>, inputs: &Inputs, e: &Enumeration, panel: &Panel, confirmed: &Confirmed) -> Result<Built, Fault> {
    let door = Door::new(p.board, p.token);
    compose_with(&door, p, inputs, e, panel, confirmed)
}

/// Prices `request`: its own shape judged here, and the board asked what it
/// prices the request at — ONE read, `publish_cost`, of the request's own
/// members ([`Request::price_frame`]).
///
/// Where the shape is past a cap a frame must be inside to parse — a list,
/// or the body — the board is not asked, and the price names those terms
/// alone. The values and the units are judged by the board's answer, never
/// ahead of it.
///
/// # Errors
///
/// The read's faults — the board unreachable or busy, the session ended —
/// and the board's refusal of the frame, [`Fault::Halt`]; an answer that is
/// no `publish_cost`, [`Fault::Shape`]. No price is guessed in their place.
pub fn price(p: &Publisher<'_>, request: &Request) -> Result<Price, Fault> {
    price_with(&Door::new(p.board, p.token), request)
}

/// Prices `request` through `door` ([`price()`]).
pub(crate) fn price_with(door: &Door<'_>, request: &Request) -> Result<Price, Fault> {
    let shape_of = request.shape();
    if !shape_of.over().is_empty() {
        return Ok(Price::of(&shape_of, None));
    }
    door.step("price");
    let frame = request.price_frame();
    let v = door.read(&frame)?;
    if let Some(refused) = Rejection::of(&v) {
        return Err(Fault::Halt(refused.refused(&v)));
    }
    let cost = answers::publish_cost(&v).ok_or_else(|| shape(&frame, &v))?;
    Ok(Price::of(&shape_of, Some(&cost)))
}

/// Builds the request through `door`, and prices it.
pub(crate) fn build_with(door: &Door<'_>, p: &Publisher<'_>, inputs: &Inputs, e: &Enumeration, panel: &Panel, confirmed: &Confirmed) -> Result<Built, Fault> {
    Ok(match compose_with(door, p, inputs, e, panel, confirmed)? {
        Built::Request(mut request) => {
            request.price = price_with(door, &request)?;
            request.as_of = request.as_of.max(door.as_of());
            Built::Request(request)
        }
        inert => inert,
    })
}

/// Builds the request through `door`, every member but its price.
fn compose_with(door: &Door<'_>, p: &Publisher<'_>, inputs: &Inputs, e: &Enumeration, panel: &Panel, confirmed: &Confirmed) -> Result<Built, Fault> {
    // The one composition the request is taken from: the answers decide
    // the selection, every offer and the formatting line before any member
    // is composed (B3-S11 P2 (i)).
    let e = &confirmed.compose(inputs, e);
    let panel = &panel.composed(inputs, e);
    if !e.placed.is_empty() && e.placed.iter().all(|placement| *placement == Placement::Absent) {
        return Err(Fault::SelectionNotArranged { index: 0 });
    }
    let trunk = inputs.doc.clone();
    // The runs as placed, each with its kept place, its place in the draft
    // and the place of the occurrence it belongs to.
    let mut placed: Vec<CarriedRun> = Vec::new();
    let mut unanswered: Vec<OwedAnswer> = Vec::new();
    let mut publish_first: Vec<PartKey> = Vec::new();
    for (i, run) in inputs.selection.iter().enumerate() {
        // The run as placed, cut around its merge records, which no
        // publication carries: no run and no kept place for one. A run that
        // carries nothing — the draft no longer arranges it, or it holds
        // merge records alone — is sent nowhere and asked nothing, so a
        // window the draft has deleted owes no answer (PUB-3.108).
        let pieces = e.pieces(i, run);
        if pieces.is_empty() {
            continue;
        }
        let occurrence = |in_draft: u64| e.placed.get(i).map_or(in_draft, |placement| placement.occurrence_at(in_draft));
        // A named draft's run — the rendering draft's or an `also` draft's —
        // is the document's own words, re-minted, and every such run names
        // the rendering draft's kept place: its own position of the run,
        // which the commit re-windows it at whichever named draft's identity
        // the run was (skep #739; an `also` draft's own place for its run
        // rides that draft's `also_places` entry, composed below). The list
        // keeps it where no other run's place overlaps it (`disjoint_places`,
        // below). The trunk's own words, held by reference, take no place.
        let native = inputs.is_named_draft(&run.origin);
        let own = trunk.as_ref() == Some(&run.origin);
        if native || own {
            for (piece, ordinal) in pieces {
                placed.push(CarriedRun { run: piece, place: native.then_some(ordinal), in_draft: ordinal, occurrence: occurrence(ordinal) });
            }
            continue;
        }
        // A window onto the person's own unpublished origin, part by part,
        // each as its answer composes it; any other window — onto a
        // published origin or another's draft — by address, no place.
        let Some(window) = e.windows.iter().find(|w| w.run == i) else {
            for (piece, ordinal) in pieces {
                placed.push(CarriedRun { run: piece, place: None, in_draft: ordinal, occurrence: occurrence(ordinal) });
            }
            continue;
        };
        for (k, part) in window.parts.iter().enumerate() {
            match compose_part(window, k, e.answer_at(window, k)) {
                // The part by reference to the published words its record
                // names — in whichever document the record's `to` lies,
                // this request's or another's — WITH ITS KEPT PLACE, the
                // rendering draft's own V-position of it, so the commit
                // re-windows the draft there through the record (the
                // link-sets design §5.5; its "KEPT PLACE sent beside it as a
                // stray's is"). A request whose only place is such a part is
                // NOT inert: the healed window is a change to the draft.
                PartComposition::ByReference(published) => placed.push(CarriedRun { run: published, place: Some(part.ordinal), in_draft: part.ordinal, occurrence: occurrence(part.ordinal) }),
                // By address onto the private origin, no place: readers see
                // a placeholder.
                PartComposition::KeptPrivate(words) => placed.push(CarriedRun { run: words, place: None, in_draft: part.ordinal, occurrence: occurrence(part.ordinal) }),
                PartComposition::LeftOut => {}
                PartComposition::PublishFirst => publish_first.push(window.key(k)),
                PartComposition::Owed => unanswered.push(OwedAnswer::of(window, k)),
            }
        }
    }
    if !unanswered.is_empty() {
        return Ok(Built::Inert(Inert::Unanswered(unanswered)));
    }
    if !publish_first.is_empty() {
        return Ok(Built::Inert(Inert::PublishFirst(publish_first)));
    }

    // The runs in the draft's order, occurrence by occurrence, as the
    // composition's selection stands: the re-statement said what `D` now
    // arranges, and the version holds that.
    placed.sort_by_key(|carried| carried.occurrence);
    let places: Vec<Option<u64>> = placed.iter().map(|carried| carried.place).collect();
    let draft_places: Vec<Option<u64>> = placed.iter().map(|carried| Some(carried.in_draft)).collect();
    let runs: Vec<Run> = placed.into_iter().map(|carried| carried.run).collect();

    // No two places of the rendering draft's list overlap, a piece's or a
    // window part's among them; each `also` draft's own kept places off its
    // image, beside it; then the twin pre-check: what each named draft's
    // records already name, by reference, every list carried beside the
    // pieces.
    let places = disjoint_places(&runs, &places);
    let also_places = also_places_of(e, &runs);
    let recomposed = twin_precheck_with(door, p, inputs, &runs, &places, &draft_places, &also_places)?;
    let (runs, places, draft_places, stray_records, also_places) = (recomposed.runs, recomposed.places, recomposed.draft_places, recomposed.stray_records, recomposed.also_places);
    let mut records: Vec<Record> = e.records.clone();
    for r in recomposed.records {
        if !records.iter().any(|k| k.link == r.link) {
            records.push(r);
        }
    }

    // The entries, and the lists beside them.
    door.step("entries");
    let lists = Lists::of(inputs, e, panel, &confirmed.switches, &records, &runs);
    let (entries, retract, read_with) = (&lists.entries, &lists.retract, &lists.read_with);

    // The daughters, the skip read first: one an active claim of the
    // person's own already names is dropped, as the board's plan drops it.
    door.step("supersede");
    let supersede = kept_daughters(door, p, &inputs.supersede)?;

    // Inert where nothing changes against the base: a place in either list
    // — the rendering draft's, or an `also` draft's re-window alone — is a
    // change to that draft, and a daughter claimed is a change to the trunk.
    // The base's image is the enumeration's where it read version ⟨k⟩.
    door.step("base");
    let fresh = runs.iter().any(|r| inputs.is_named_draft(&r.origin));
    let placed = places.iter().any(Option::is_some) || also_places.iter().any(AlsoPlaces::carries_a_place);
    // The base's image over the positions the copy took, read once where a
    // base stands: the enumeration's where it read that member.
    let base_image: Option<Vec<IRun>> = match &inputs.base {
        Some(base) => Some(match e.base.as_ref().filter(|known| known.is_of(base)) {
            Some(known) => known.image.clone(),
            None => door.image(&base.0.to_string(), 1, base.1)?,
        }),
        None => None,
    };
    if !fresh && entries.is_empty() && retract.is_empty() && read_with.is_empty() && supersede.is_empty() && inputs.mint.is_none() && !placed {
        if let Some(image) = &base_image {
            let same = image.len() == runs.len() && image.iter().zip(&runs).all(|(a, r)| a.prefix == r.chain() && a.first == r.i_start && a.width == r.width);
            if same {
                return Ok(Built::Inert(Inert::Unchanged));
            }
        }
    }

    // THE FORM. A publication with a base names its CHANGE: the runs are cut
    // against the base's image (`cut_against`) and the request carries the
    // stretches and the runs that replace them, every list beside the runs
    // cut to those runs. A run rides the request, whatever the base holds,
    // where it is a named draft's — the commit re-mints it — where a list
    // carries its kept place or a record covers it, and where an entry any
    // row could send counts positions over it: an end on this shot's new
    // words is spelled by the request's own positions, which only its own
    // runs have. The whole arrangement is sent where there is no base; where
    // the base is the bare document — a draft begun before its first
    // version, whose base's own arrangement no read here takes: the image
    // above floats to the head once a member stands, and a cut against it
    // would name stretches of another list; where the base stands one short
    // of the chain's bound, so this member ends the chain
    // (`WHOLE_FORM_EVERY`); where the cut replaces the base whole; and where
    // it names more stretches than one list carries.
    let is_member = |base: &Address| {
        let text = base.to_string();
        super::trunk_of(&text).is_some_and(|trunk| trunk != text)
    };
    let cut = match (&inputs.base, &base_image) {
        (Some(base), Some(image)) if is_member(&base.0) => {
            let depth = door.metadata(&base.0.to_string())?.chain_depth.unwrap_or(0);
            if depth.saturating_add(1) >= WHOLE_FORM_EVERY {
                None
            } else {
                // Every row switched on: the positions any entry's end may
                // count are held in the request whatever is switched later.
                let mut every = confirmed.switches.clone();
                every.on.extend(panel.rows.iter().map(|row| row.home.clone()));
                let counted = member_end_runs(&Lists::of(inputs, e, panel, &every, &records, &runs).entries, &runs);
                let pinned = |index: usize| {
                    inputs.is_named_draft(&runs[index].origin)
                        || places.get(index).copied().flatten().is_some()
                        || also_places.iter().any(|a| a.places.get(index).copied().flatten().is_some())
                        || stray_records.get(index).is_some_and(|records| *records > 0)
                        || counted.contains(&index)
                };
                let cut = cut_against(image, base.1, &runs, &pinned);
                let whole = cut.stretches == [Stretch { start: 1, width: base.1, count: runs.len() }];
                (!whole && cut.stretches.len() <= super::enumerate::MAX_WIRE_LIST).then_some(cut)
            }
        }
        _ => None,
    };
    let (runs, places, draft_places, stray_records, also_places, stretches, lists) = match cut {
        Some(cut) => {
            let runs = cut.of(&runs);
            let also_places = also_places.iter().map(|a| AlsoPlaces { draft: a.draft.clone(), places: cut.of(&a.places) }).collect();
            // The entries again, each end spelled over the runs the request
            // now carries: a position counted is a position of these runs.
            let lists = Lists::of(inputs, e, panel, &confirmed.switches, &records, &runs);
            (runs, cut.of(&places), cut.of(&draft_places), cut.of(&stray_records), also_places, cut.stretches, lists)
        }
        None => (runs, places, draft_places, stray_records, also_places, Vec::new(), lists),
    };
    let Lists { entries, unspellable, retract, originals, read_with, count } = lists;

    // The body's pieces: the values of every copied run the request carries
    // — a named draft's, the trunk's own — read through the rendering draft,
    // which arranges them at their places; a window by address. A run the
    // base holds where the member does is in no stretch, and no value of it
    // is read.
    door.step("values");
    let draft = inputs.draft.to_string();
    let mut pieces = Vec::with_capacity(runs.len());
    for (k, run) in runs.iter().enumerate() {
        let copied = inputs.is_named_draft(&run.origin) || trunk.as_ref() == Some(&run.origin);
        match (copied, draft_places[k]) {
            (true, Some(place)) => pieces.push(Piece::Values(door.values(&draft, place, run.width)?)),
            (true, None) => pieces.push(Piece::Values(door.values(&run.origin.to_string(), run.i_start, run.width)?)),
            (false, _) => pieces.push(Piece::Window { start: parse_address(&run.i_start_text()).expect("a run's address"), width: run.width }),
        }
    }

    let request = Request {
        doc: inputs.doc.clone(),
        mint: inputs.mint.clone(),
        claim: inputs.claim,
        base: inputs.base.clone(),
        stretches,
        draft: Some(inputs.draft.clone()),
        also: inputs.also.clone(),
        // A publication of the draft itself: its base moves to the member.
        keep_base: false,
        runs,
        places,
        also_places,
        stray_records,
        pieces,
        entries,
        retract,
        originals,
        read_with,
        supersede,
        unspellable,
        id: fresh_id(),
        count,
        price: Price::default(),
        as_of: door.as_of().max(e.as_of),
    };
    Ok(Built::Request(Box::new(request)))
}

/// Returns the runs of `runs` a member-position end of `entries` counts a
/// position over, by index: what must ride a request for those ends to be
/// spelled over its own runs.
fn member_end_runs(entries: &[Entry], runs: &[Run]) -> BTreeSet<usize> {
    let mut at = 1u64;
    let spans: Vec<(u64, u64)> = runs
        .iter()
        .map(|run| {
            let span = (at, at.saturating_add(run.width));
            at = span.1;
            span
        })
        .collect();
    let mut counted = BTreeSet::new();
    for entry in entries {
        for end in [&entry.from, &entry.to, &entry.ty] {
            let End::Member(positions) = end else { continue };
            for &(ordinal, width) in positions {
                let reach = ordinal.saturating_add(width);
                counted.extend(spans.iter().enumerate().filter(|(_, (first, past))| *first < reach && ordinal < *past).map(|(index, _)| index));
            }
        }
    }
    counted
}

/// The lists a request carries beside its runs, as the switches decide
/// them over one composition.
struct Lists {
    /// The `links` entries.
    entries: Vec<Entry>,
    /// The switched-on links left out for want of one form, with why.
    unspellable: Vec<(Address, Unspellable)>,
    /// The `retract` entries: the job list's marks.
    retract: Vec<Address>,
    /// The `originals` rider the marks end.
    originals: Vec<OriginalEntry>,
    /// The `read_with` entries, the count's.
    read_with: Vec<Address>,
    /// The count the rows as switched give.
    count: Count,
}

impl Lists {
    /// Returns the lists of a request whose runs are `runs`: the formatting
    /// line's marks into the member and each switched-on private row's
    /// links into its destination, each end spelled through the walk of
    /// `records` over `runs`, a link no one form spells left out with why;
    /// the job list's retractions and the originals they end; and the
    /// count, whose read-withs the request carries. Reads nothing.
    fn of(inputs: &Inputs, e: &Enumeration, panel: &Panel, switches: &Switches, records: &[Record], runs: &[Run]) -> Lists {
        let mut entries: Vec<Entry> = Vec::new();
        let mut unspellable: Vec<(Address, Unspellable)> = Vec::new();
        let ctx = SpellContext { walk: RecordWalk::composed(inputs, records, e), runs, held_back: e.held_back_words(), placeholders: e.placeholder_words() };
        let mut add = |candidate: usize, home: EntryHome| {
            let c = &e.candidates[candidate];
            let formatting = is_formatting(&c.value);
            let ends = (spell_end(&c.value.from, &c.via, &ctx, formatting), spell_end(&c.value.to, &c.via, &ctx, formatting), spell_type(&c.value.ty));
            match ends {
                (Ok(from), Ok(to), Ok(ty)) => entries.push(Entry { home, from, to, ty, old: Some(c.link.clone()), candidate }),
                (Err(why), _, _) | (_, Err(why), _) | (_, _, Err(why)) => unspellable.push((c.link.clone(), why)),
            }
        };
        for &mark in &panel.formatting.marks {
            add(mark, EntryHome::Member);
        }
        for row in &panel.rows {
            if matches!(row.kind, RowKind::Public { .. }) || !switches.on.contains(&row.home) {
                continue;
            }
            let home = match switches.destination(&row.home) {
                Destination::Member => EntryHome::Member,
                Destination::Set(s) => EntryHome::Set(s),
            };
            for &i in &row.links {
                add(i, home.clone());
            }
        }
        let job_list = panel.formatting.job_list();
        let retract: Vec<Address> = job_list.iter().map(|r| r.mark.clone()).collect();
        let originals = originals_of(&job_list);
        let count = count(panel, switches, inputs);
        let read_with = count.read_with.clone();
        Lists { entries, unspellable, retract, originals, read_with, count }
    }
}

/// Composes each `also` draft's own kept places over `runs`, off its image
/// (the wire's `also_places`; skep #739), in `also`'s order.
///
/// At a run of THAT draft's identity: the V-ordinal its image arranges the
/// run at, found as the rendering draft's places are (`place_selection`:
/// whole and in order, the k-th equal run the k-th occurrence, no two
/// places of the list overlapping, `disjoint_places`); `None` where its
/// image does not arrange it whole — moved, split or deleted since the
/// panel, a place the client is not sure of, so the draft is left as it
/// stands at that run and the board's fence meets it at the draft's own
/// next shot — and where its every place overlaps another run's in the
/// list. `None` at every other run — the rendering draft's own,
/// the trunk's, a window's, another `also` draft's — whose place is no
/// business of this draft's list; a stray of the draft's own (published
/// words it arranges that a record names) is not composed here, and heals
/// at its own shot. Where a draft arranges a run's identity twice, its image
/// answers each place and the k-th equal run in `runs` takes the k-th
/// (`place_selection`); a place no run in `runs` takes is left standing, as
/// a stray is.
pub(crate) fn also_places_of(e: &Enumeration, runs: &[Run]) -> Vec<AlsoPlaces> {
    e.also
        .iter()
        .map(|a| {
            let placed = place_selection(&a.image, runs);
            let places: Vec<Option<u64>> = runs
                .iter()
                .zip(&placed)
                .map(|(run, placement)| match placement {
                    Placement::Whole { ordinal } if run.origin == a.draft => Some(*ordinal),
                    _ => None,
                })
                .collect();
            let places = disjoint_places(runs, &places);
            AlsoPlaces { draft: a.draft.clone(), places }
        })
        .collect()
}

/// What spelling an end needs.
struct SpellContext<'a> {
    /// The walk through the records — the enumeration's and the twin
    /// pre-check's — and the window parts taken by their counterpart, which
    /// reads a candidate's ends as the filter reads them.
    walk: RecordWalk<'a>,
    runs: &'a [Run],
    /// The words no answer publishes: every window part left out, answered
    /// publish-first or awaiting its answer.
    held_back: Vec<ISpan>,
    /// The words kept behind a placeholder, which no formatting mark is
    /// spelled onto.
    placeholders: Vec<ISpan>,
}

impl SpellContext<'_> {
    /// Returns `span` less the words the end may not be spelled on: those
    /// no answer publishes, and for a formatting mark those behind a
    /// placeholder.
    fn kept(&self, span: &ISpan, formatting: bool) -> Vec<ISpan> {
        let mut cut = self.held_back.clone();
        if formatting {
            cut.extend(self.placeholders.iter().cloned());
        }
        span.less(&cut)
    }
}

/// Spells one end of a candidate reached `via` from its stored slot.
///
/// The address form where every span is a unit span at a non-content
/// address. Otherwise each span is read in the pieces the walk through the
/// records and the parts taken by their counterpart reads it in
/// (`RecordWalk`), in the stored order, each piece less the words the end
/// may not be spelled on ([`SpellContext::kept`]): a piece a record maps is
/// the published words it became, a piece of a named draft's own words no
/// record maps is this shot's new words where the shot's runs hold them
/// and is cut where they do not, and any other piece is kept as stored. The
/// end is the member-position form where a piece lies on this shot's new
/// words, every other piece then one the member holds; else the I-span form
/// over the pieces kept, or over the stored spans as written where every
/// piece was cut.
fn spell_end(slot: &[LinkSpan], via: &Via, ctx: &SpellContext<'_>, formatting: bool) -> Result<End, Unspellable> {
    if slot.is_empty() {
        return Ok(End::Addrs(Vec::new()));
    }
    let spans: Vec<Option<ISpan>> = slot.iter().map(ISpan::of).collect();
    if spans.iter().all(Option::is_none) {
        return Ok(End::Addrs(slot.iter().map(|s| s.start.clone()).collect()));
    }
    if spans.iter().any(Option::is_none) {
        return Err(Unspellable::MixedAddress);
    }
    let spans: Vec<ISpan> = spans.into_iter().flatten().collect();
    // The pieces the end sends, in the stored order, each with whether it
    // lies on this shot's new words.
    let mut sent: Vec<(ISpan, bool)> = Vec::new();
    for s in &spans {
        for piece in ctx.walk.pieces(s, via) {
            for p in ctx.kept(&piece.span, formatting) {
                if piece.mapped || !ctx.walk.is_named_chain(&p.chain) {
                    sent.push((p, false));
                    continue;
                }
                // The shot's runs of the piece's own chain hold the named
                // draft's new words; the rest is left out and cut.
                let native_runs: Vec<&Run> = ctx.runs.iter().filter(|r| r.chain() == p.chain).collect();
                let mut cursor = p.first;
                while cursor < p.reach() {
                    match native_runs.iter().find(|r| r.i_start <= cursor && cursor < r.reach()) {
                        Some(run) => {
                            let end = run.reach().min(p.reach());
                            sent.push((ISpan { chain: p.chain.clone(), first: cursor, width: end - cursor }, true));
                            cursor = end;
                        }
                        None => cursor = native_runs.iter().filter(|r| r.i_start > cursor).map(|r| r.i_start).min().unwrap_or(p.reach()).min(p.reach()),
                    }
                }
            }
        }
    }
    if sent.iter().any(|(_, new)| *new) {
        // Every other piece of the end must be one the member holds.
        if sent.iter().any(|(s, new)| !new && !s.within(ctx.runs)) {
            return Err(Unspellable::MixedForms);
        }
        let pieces: Vec<ISpan> = sent.into_iter().map(|(s, _)| s).collect();
        let canonical = canonical_member_spans(ctx.runs, &pieces).ok_or(Unspellable::MixedForms)?;
        return Ok(End::Member(canonical));
    }
    if sent.is_empty() {
        // Wholly on words this shot leaves out: decision 5's far end, or
        // words no answer publishes, written as it is.
        return Ok(End::Spans(spans));
    }
    Ok(End::Spans(sent.into_iter().map(|(s, _)| s).collect()))
}

/// Spells the type slot: the address form where every span is a unit span,
/// else the I-span form verbatim.
fn spell_type(slot: &[LinkSpan]) -> Result<End, Unspellable> {
    if slot.iter().all(LinkSpan::is_unit) {
        return Ok(End::Addrs(slot.iter().map(|s| s.start.clone()).collect()));
    }
    let spans: Vec<ISpan> = slot.iter().map(ISpan::of).collect::<Option<_>>().ok_or(Unspellable::MixedAddress)?;
    Ok(End::Spans(spans))
}
